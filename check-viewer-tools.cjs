const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000/';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    const errors = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**://tile.openstreetmap.org/**', route => route.abort());
    await page.goto(base);
    await page.waitForFunction(() => viewerLayers);
    const parser = await page.evaluate(() => {
      const valid = parseAddressCsv('\uFEFF주소\r\n"서울, 주소"\r\n"따옴표 ""주소"""\r\n');
      const invalid = ['이름,주소\na,b', '주소\n"닫히지 않음', '주소\n"주소"x', '주소\n"두\n줄"', '주소\n' + 'a'.repeat(301), '주소\n' + Array(101).fill('주소').join('\n'), '주소\n'];
      return { valid, rejected: invalid.map(text => { try { parseAddressCsv(text); return false; } catch { return true; } }), formula: csvCell('=1+1'), carriage: csvCell('a\rb') };
    });
    assert.deepEqual(parser.valid, ['서울, 주소', '따옴표 "주소"']);
    assert.ok(parser.rejected.every(Boolean));
    assert.equal(parser.formula, "'=1+1");
    assert.equal(parser.carriage, '"a\rb"');
    await page.evaluate(() => {
      const rings = [[[127,37],[127.01,37],[127.01,37.01],[127,37.01],[127,37]]];
      renderViewer({ head: { UNIT_TYPE: 'tong' }, shapes: { 1: { rings, name: '', banShapes: { 2: { rings } } } } }, null, '인쇄 시험 지도');
    });
    await page.locator('#addressForm details summary').click();
    await page.locator('#addressKey').fill('test-only-batch-key');
    await page.locator('#batchTools summary').click();
    let scenario = 'ok';
    await page.route('https://api.vworld.kr/req/address?**', async route => {
      const url = new URL(route.request().url());
      requests.push(url.searchParams.get('address'));
      let response = { status: 'OK', result: { point: { x: '127.005', y: '37.005' } } };
      if (url.searchParams.get('address') === '없는 주소') response = { status: 'NOT_FOUND' };
      if (scenario === 'error') response = { status: 'ERROR', error: { code: 'OVER_REQUEST_LIMIT' } };
      if (scenario === 'slow') await new Promise(resolve => setTimeout(resolve, 800));
      await route.fulfill({ contentType: 'application/javascript', body: url.searchParams.get('callback') + '(' + JSON.stringify({ response }) + ');' }).catch(() => {});
    });
    const upload = async text => {
      await page.locator('#batchFile').setInputFiles({ name: 'addresses.csv', mimeType: 'text/csv', buffer: Buffer.from(text) });
      await page.waitForFunction(() => batchRows.length > 0);
    };
    await upload('주소\n=1+1\n=1+1\n없는 주소');
    assert.equal(requests.length, 0);
    await page.locator('#batchStart').click();
    await page.waitForFunction(() => !batchRunning && batchResults.length === 3);
    assert.equal(requests.length, 2);
    assert.equal(await page.evaluate(() => batchResults[0][1]), '1통 2반');
    assert.match(await page.evaluate(() => batchResults[2][2]), /찾지 못/);
    const download = page.waitForEvent('download');
    await page.locator('#batchExport').click();
    const file = await download;
    const csv = await fs.readFile(await file.path(), 'utf8');
    assert.ok(csv.includes("'=1+1"));
    assert.ok(csv.includes('1통 2반'));
    assert.ok(!csv.includes('test-only-batch-key'));
    assert.ok(!csv.includes('127.005'));
    assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes('=1+1') || JSON.stringify(localStorage).includes('test-only-batch-key')), false);
    scenario = 'error';
    await page.locator('#batchStart').click();
    await page.waitForFunction(() => !batchRunning && batchResults.length === 1);
    assert.match(await page.locator('#batchStatus').textContent(), /오류로 중단/);
    scenario = 'slow';
    await page.locator('#batchStart').click();
    await page.locator('#batchCancel').click();
    await page.waitForTimeout(1000);
    assert.equal(await page.evaluate(() => batchResults.length), 0);
    await page.locator('#batchStart').click();
    await page.locator('#addressKey').fill('new-test-key');
    await page.waitForTimeout(1000);
    assert.equal(await page.evaluate(() => batchRunning || batchResults.length > 0), false);
    const original = await page.evaluate(() => ({ zoom: viewerMap.getZoom(), lat: viewerMap.getCenter().lat }));
    await page.emulateMedia({ media: 'print' });
    await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')));
    assert.equal(await page.locator('#panel').isVisible(), false);
    assert.equal(await page.locator('#printHeading').isVisible(), true);
    assert.equal(await page.locator('#printTitle').textContent(), '인쇄 시험 지도');
    assert.equal(await page.locator('.leaflet-control-attribution').isVisible(), true);
    assert.ok((await page.locator('.leaflet-tooltip').allTextContents()).some(text => text.includes('2반')));
    const pdf = await page.pdf({ preferCSSPageSize: true, printBackground: true });
    assert.equal(pdf.subarray(0, 4).toString(), '%PDF');
    await page.emulateMedia({ media: 'screen' });
    await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
    assert.equal(await page.evaluate(() => viewerMap.getZoom()), original.zoom);
    assert.ok(Math.abs(await page.evaluate(() => viewerMap.getCenter().lat) - original.lat) < 0.00001);
    await page.locator('#batchClear').click();
    assert.equal(await page.evaluate(() => batchRows.length + batchResults.length), 0);
    assert.deepEqual(errors, []);
    console.log('PASS CSV validation, no upload before start, deduplication, cancellation, quota stop, safe export, no persistence, print labels/attribution/PDF and map restoration');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
