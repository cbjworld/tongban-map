const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000/';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    const errors = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/vworld\.kr/.test(request.url())) requests.push(request.url()); });
    await page.route('**://tile.openstreetmap.org/**', route => route.abort());
    await page.goto(base);
    await page.waitForFunction(() => viewerLayers);
    assert.equal(await page.locator('#addressForm, #batchTools, input[type=password]').count(), 0);
    await page.evaluate(() => {
      const rings = [[[127,37],[127.01,37],[127.01,37.01],[127,37.01],[127,37]]];
      renderViewer({ head: { UNIT_TYPE: 'tong' }, shapes: { 1: { rings, labelPoint: [127.002,37.002], name: '', banShapes: { 2: { rings } } } } }, null, '인쇄 시험 지도');
      const group = viewerLayers.getLayers()[0];
      if (Number(viewerMap.getPane('viewerTong').style.zIndex) <= Number(viewerMap.getPane('viewerBan').style.zIndex)) throw Error('Viewer tong boundary is not above ban');
      const marker = group.getLayers().find(layer => layer instanceof L.CircleMarker);
      if (!marker || !turf.booleanPointInPolygon(turf.point([marker.getLatLng().lng, marker.getLatLng().lat]), turf.polygon(rings))) throw Error('Viewer label outside boundary');
      if (marker.getLatLng().lng !== 127.002 || marker.getLatLng().lat !== 37.002) throw Error('Viewer ignored saved label');
      const polygon = group.getLayers().find(layer => layer instanceof L.GeoJSON);
      const expected = document.createElement('span'); expected.style.backgroundColor = unitColors(1).label;
      if (polygon.getLayers()[0].options.fillColor !== unitColors(1).fill || marker.getTooltip().getContent().style.backgroundColor !== expected.style.backgroundColor) throw Error('Viewer colors differ from editor');
    });
    const toggle = page.getByRole('checkbox', { name: '1통 표시' });
    await toggle.uncheck();
    assert.equal(await page.evaluate(() => viewerLayers.getLayers().length), 0);
    await page.getByRole('button', { name: '1통', exact: true }).click();
    assert.equal(await toggle.isChecked(), true);
    assert.equal(await page.evaluate(() => viewerLayers.getLayers().length), 1);
    await page.locator('#viewerFile').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{invalid') });
    await page.waitForFunction(() => document.getElementById('viewerStatus').textContent.includes('불러오기 실패'));
    assert.equal(await page.evaluate(() => viewerData.shapes[1].rings.length), 1);
    const original = await page.evaluate(() => ({ zoom: viewerMap.getZoom(), lat: viewerMap.getCenter().lat }));
    await page.emulateMedia({ media: 'print' });
    await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')));
    assert.equal(await page.locator('#panel').isVisible(), false);
    assert.equal(await page.locator('#printHeading').isVisible(), true);
    assert.equal(await page.locator('#printTitle').textContent(), '인쇄 시험 지도');
    assert.equal(await page.locator('.leaflet-control-attribution').isVisible(), true);
    assert.ok((await page.locator('.leaflet-tooltip').allTextContents()).some(text => text.includes('2반')));
    const pdf = await page.pdf({ preferCSSPageSize: true, printBackground: true });
    assert.equal(pdf.subarray(0, 4).toString(), '%PDF');
    await page.emulateMedia({ media: 'screen' });
    await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
    assert.equal(await page.evaluate(() => viewerMap.getZoom()), original.zoom);
    assert.ok(Math.abs(await page.evaluate(() => viewerMap.getCenter().lat) - original.lat) < 0.00001);
    const otherSido = await page.evaluate(() => viewerRegions.find(region => region.sido !== document.getElementById('sidoSelect').value).sido);
    await page.selectOption('#sidoSelect', otherSido);
    assert.equal(await page.evaluate(() => viewerData), null);
    assert.equal(await page.locator('#viewerTitle').textContent(), '');
    assert.match(await page.locator('#viewerStatus').textContent(), /읍면동을 선택/);
    const delayedRegion = await page.evaluate(() => viewerRegions.find(region => region.sido === document.getElementById('sidoSelect').value));
    await page.route('**/data/regions/' + delayedRegion.code + '.json', async route => {
      await new Promise(resolve => setTimeout(resolve, 400));
      await route.continue();
    });
    await page.evaluate(code => { loadViewerRegion(code); }, delayedRegion.code);
    await page.selectOption('#sidoSelect', '');
    await page.waitForTimeout(700);
    assert.equal(await page.evaluate(() => viewerData), null);
    assert.equal(await page.locator('#viewerTitle').textContent(), '');
    assert.deepEqual(errors, []);
    assert.equal(requests.length, 0);
    console.log('PASS key-free viewer, no VWorld requests, print labels/attribution/PDF and map restoration');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
